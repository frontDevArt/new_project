-- Версия 6: дата возврата объявления на ленту.
--
-- listings.returned_at — когда снятое объявление снова встретилось на ленте.
--   Без своей колонки возврат не выбрать ничем: `gone_at` у вернувшегося
--   обнулён, `first_seen` не двигался, а `last_seen` прогон двигает всей
--   ленте разом — по нему возврат неотличим от обычной встречи. Отдельная
--   дата нужна разделу «Вернулись» в `changes` ровно так же, как `gone_at`
--   нужна разделу «Снято».
--   Обнуляется при следующем снятии: колонка отвечает на вопрос «когда это
--   объявление вернулось», а не «когда оно возвращалось когда-то».

ALTER TABLE listings ADD COLUMN returned_at TEXT;

CREATE INDEX IF NOT EXISTS idx_listings_returned_at ON listings(returned_at);
